    private static void GenerateIncludeNavigationsMethod(StringBuilder sb, string entityName)
    {
        sb.AppendLine($"        private static IQueryable<{entityName}> IncludeNavigations(IQueryable<{entityName}> query, Type entityType, int depth, HashSet<Type>? visitedTypes = null)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (depth <= 0) return query;");
        sb.AppendLine();
        sb.AppendLine("            visitedTypes ??= new HashSet<Type>();");
        sb.AppendLine("            if (!visitedTypes.Add(entityType)) return query; // Prevent circular references");
        sb.AppendLine();
        sb.AppendLine("            var navigationProperties = entityType.GetProperties()");
        sb.AppendLine("                .Where(p => (p.PropertyType.IsClass && p.PropertyType != typeof(string)) ||");
        sb.AppendLine("                           (p.PropertyType.IsGenericType && typeof(IEnumerable).IsAssignableFrom(p.PropertyType)));");
        sb.AppendLine();
        sb.AppendLine("            foreach (var nav in navigationProperties)");
        sb.AppendLine("            {");
        sb.AppendLine("                var navPath = nav.Name;");
        sb.AppendLine("                query = query.Include(navPath);");
        sb.AppendLine();
        sb.AppendLine("                if (depth > 1)");
        sb.AppendLine("                {");
        sb.AppendLine("                    var navType = nav.PropertyType.IsGenericType");
        sb.AppendLine("                        ? nav.PropertyType.GetGenericArguments()[0]");
        sb.AppendLine("                        : nav.PropertyType;");
        sb.AppendLine();
        sb.AppendLine("                    if (navType.IsClass && navType != typeof(string) && !visitedTypes.Contains(navType))");
        sb.AppendLine("                    {");
        sb.AppendLine("                        var nestedNavs = navType.GetProperties()");
        sb.AppendLine("                            .Where(p => (p.PropertyType.IsClass && p.PropertyType != typeof(string)) ||");
        sb.AppendLine("                                       (p.PropertyType.IsGenericType && typeof(IEnumerable).IsAssignableFrom(p.PropertyType)));");
        sb.AppendLine();
        sb.AppendLine("                        foreach (var nestedNav in nestedNavs)");
        sb.AppendLine("                        {");
        sb.AppendLine("                            var nestedPath = $\"{navPath}.{nestedNav.Name}\";");
        sb.AppendLine("                            query = query.Include(nestedPath);");
        sb.AppendLine("                        }");
        sb.AppendLine("                    }");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine("            return query;");
        sb.AppendLine("        }");
    }

    private static T GetEnumValue<T>(AttributeData attributeData, string propertyName, T defaultValue)
    {
        foreach (var namedArg in attributeData.NamedArguments)
        {
            if (namedArg.Key == propertyName && namedArg.Value.Value != null)
            {
                return (T)namedArg.Value.Value;
            }
        }
        return defaultValue;
    }
}

internal class ServiceInfo
{
    public string ClassName { get; set; } = string.Empty;
    public string Namespace { get; set; } = string.Empty;
    public int Actions { get; set; }
    public bool HasTenantId { get; set; }
}